"""
Unified reproducible evaluation pipeline (revision build).

Everything the manuscript reports is produced HERE, from raw predictions, in one
run. No hardcoded metrics, no mock distributions. Figures are generated by
generate_figures.py strictly from the artifacts this script writes.

Reviewer fixes implemented by construction:
  - Leakage-free preprocessing: encoding/scaling fit inside each CV fold
    (sklearn Pipeline/ColumnTransformer).                              [R3-6]
  - Age treated as a protected attribute -> excluded from predictors, so it
    cannot appear as a model feature in SHAP/permutation.              [R3-4]
  - CatBoost uses native categorical handling (cat_features); LogReg/RF use
    one-hot. Rationale now matches implementation.                     [R3-8]
  - Explicit, logged hyperparameters for every model.                  [R3-7]
  - Class weighting run as a sensitivity (weighted vs unweighted) with its
    effect on calibration measured.                                    [R3-11]
  - Clean leave-group-out compensation ablation, both directions, same splits,
    same settings.                                                     [R3-5]
  - Real bootstrap CI (method logged), 7-seed sweep, SHAP + permutation with
    faithfulness/stability/sanity checks, Cramer's V, disparate-impact ratios,
    DBSCAN/KMeans/PCA-KMeans/GMM, MI with estimator + permutation null,
    ECE with bootstrap CI and adaptive binning, threshold sensitivity,
    train/test overfitting gap.               [R1-2, R1-3, R1-5, R1-6, R3-2/3/9/10/12]

Primary result = stratified 5-fold CV (seed 42). A single stratified holdout is
reported as a robustness illustration (confusion matrix, bootstrap, SHAP).
"""

