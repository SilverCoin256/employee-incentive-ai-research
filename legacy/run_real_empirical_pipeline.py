def load_data():
    df = pd.read_csv(DATA, encoding="utf-8-sig")          # strips BOM on 'Age'
    df.columns = [c.strip() for c in df.columns]
    y = (df["Attrition"].astype(str).str.strip() == "Yes").astype(int).values

    # constant / identifier columns
    drop_const = [c for c in ["EmployeeCount", "EmployeeNumber", "Over18",
                              "StandardHours"] if c in df.columns]
    protected = ["Gender", "Age", "MaritalStatus"]

    # ── structural indices (row-wise, parameter-free -> no leakage) ──────────
    df["OvertimeFrequency"]       = (df["OverTime"] == "Yes").astype(int)
    df["SatisfactionJobLevel"]    = df["JobSatisfaction"] * df["JobLevel"]
    df["TenurePromotionRatio"]    = df["YearsAtCompany"] / (df["YearsSinceLastPromotion"] + 1)
    df["OvertimeBalanceRatio"]    = df["OvertimeFrequency"] / (df["WorkLifeBalance"] + 1)
    df["CompensationProgression"] = df["MonthlyIncome"] / (df["YearsAtCompany"] + 1)
    df["PerfCompAlignment"]       = df["PerformanceRating"] * df["MonthlyIncome"]
    df["WorkArrangement"]         = df["BusinessTravel"].map(
        {"Non-Travel": 0, "Travel_Rarely": 1, "Travel_Frequently": 2}).fillna(0)
    df["MultiSatisfaction"]       = (df["JobSatisfaction"] +
                                     df["EnvironmentSatisfaction"] +
                                     df["RelationshipSatisfaction"]) / 3

    # protected attribute encodings (for fairness only)
    prot = pd.DataFrame({
        "gender":  (df["Gender"] == "Male").astype(int).values,
        "marital": df["MaritalStatus"].astype("category").cat.codes.values,
        "ageband": pd.cut(df["Age"], bins=[17, 29, 39, 49, 120],
                          labels=[0, 1, 2, 3]).astype(int).values,
        "compband": pd.qcut(df["MonthlyIncome"], 4, labels=[0, 1, 2, 3]).astype(int).values,
        "dept":    df["Department"].astype("category").cat.codes.values,
    })

    X = df.drop(columns=["Attrition"] + drop_const + protected)
    cat_cols = X.select_dtypes(include=["object", "category", "string"]).columns.tolist()
    # ensure categorical columns are plain python strings for CatBoost
    for c in cat_cols:
        X[c] = X[c].astype(str)
    num_cols = [c for c in X.columns if c not in cat_cols]

    # compensation feature group for the ablation (explicit, logged)
    comp_group = ["MonthlyIncome", "MonthlyRate", "DailyRate", "HourlyRate",
                  "PercentSalaryHike", "StockOptionLevel",
                  "CompensationProgression", "PerfCompAlignment"]
    comp_group = [c for c in comp_group if c in X.columns]
    return df, X, y, cat_cols, num_cols, comp_group, prot


# ─────────────────────────────────────────────────────────────────────────────
# Model builders (leakage-free; fit inside each fold)
# ─────────────────────────────────────────────────────────────────────────────
CATBOOST_PARAMS = dict(iterations=400, learning_rate=0.05, depth=6,
                       random_seed=RNG, verbose=0, allow_writing_files=False)
RF_PARAMS = dict(n_estimators=400, max_depth=None, min_samples_leaf=2,
                 random_state=RNG, n_jobs=-1)
LOGREG_PARAMS = dict(max_iter=2000, C=1.0, random_state=RNG)


def make_sklearn_pipe(kind, cat_cols, num_cols):
    if kind == "logreg":
        pre = ColumnTransformer([
            ("num", StandardScaler(), num_cols),
            ("cat", OneHotEncoder(handle_unknown="ignore"), cat_cols)])
        clf = LogisticRegression(**LOGREG_PARAMS)
    elif kind == "rf":
        pre = ColumnTransformer([
            ("num", "passthrough", num_cols),
            ("cat", OneHotEncoder(handle_unknown="ignore"), cat_cols)])
        clf = RandomForestClassifier(**RF_PARAMS)
    elif kind == "dummy":
        pre = ColumnTransformer([
            ("num", "passthrough", num_cols),
            ("cat", OneHotEncoder(handle_unknown="ignore"), cat_cols)])
        clf = DummyClassifier(strategy="prior")
    else:
        raise ValueError(kind)
    return Pipeline([("pre", pre), ("clf", clf)])


def fit_catboost(Xtr, ytr, cat_cols, class_weights=None):
    params = dict(CATBOOST_PARAMS)
    if class_weights is not None:
        params["class_weights"] = class_weights
    m = CatBoostClassifier(**params)
    m.fit(Pool(Xtr, ytr, cat_features=cat_cols))
    return m


